/**
 * Emit the runtime-owned cheap drizzle surface from the seam table.
 * Universe `.d.ts` is an existence check only (name is exported).
 */
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  NAME_SEAMS,
  QUERY_ANY_WHY,
  SUPPORT,
  SUPPORT_WHY,
} from "./drizzle-seams.mjs";
import { universeNodeModules } from "./universe.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const generatedDir = join(root, "src", "generated", "types-pack");
export const GENERATED_SURFACE_REL =
  "framework/runtime/src/generated/types-pack/drizzle-orm.d.ts";
export const GENERATED_SURFACE_ABS = join(generatedDir, "drizzle-orm.d.ts");

const UNIVERSE_DRIZZLE = join(universeNodeModules, "drizzle-orm");

const DEAD_DIALECTS = new Set([
  "pg-core",
  "mysql-core",
  "gel-core",
  "singlestore-core",
]);

const EXPORT_DECL = (name) =>
  new RegExp(
    String.raw`export\s+declare\s+(?:async\s+)?(?:function|const|class|type|interface)\s+${name}\b|export\s+declare\s+const\s+${name}\s*:|export\s+type\s+${name}\b|export\s+\{[^}]*\b${name}\b`
  );

const DRIZZLE_VFS_PREFIX = "/node_modules/drizzle-orm";

/** @param {string} vfsPath */
export function isDrizzleDeclVfsPath(vfsPath) {
  if (
    !(
      vfsPath === DRIZZLE_VFS_PREFIX ||
      vfsPath.startsWith(`${DRIZZLE_VFS_PREFIX}/`)
    )
  ) {
    return false;
  }
  if (vfsPath.endsWith("package.json") || vfsPath.endsWith(".json")) {
    return false;
  }
  return /\.d\.[cm]?ts$/i.test(vfsPath) || /\.(mts|cts|ts)$/i.test(vfsPath);
}

/**
 * @param {string} dir
 * @param {string[]} out
 */
function walkDts(dir, out) {
  let ents;
  try {
    ents = readdirSync(dir);
  } catch {
    return;
  }
  for (const ent of ents) {
    if (DEAD_DIALECTS.has(ent)) {
      continue;
    }
    const p = join(dir, ent);
    const st = statSync(p);
    if (st.isDirectory()) {
      walkDts(p, out);
    } else if (ent.endsWith(".d.ts")) {
      out.push(p);
    }
  }
}

/**
 * @param {string} name
 * @returns {{ name: string, file: string, snippet: string } | null}
 */
function findExport(name) {
  if (!existsSync(UNIVERSE_DRIZZLE)) {
    throw new Error(
      `drizzle-orm missing from universe: ${UNIVERSE_DRIZZLE} — run install-universe`
    );
  }
  const files = [];
  walkDts(UNIVERSE_DRIZZLE, files);
  const exportRe = EXPORT_DECL(name);
  for (const file of files) {
    const text = readFileSync(file, "utf8");
    const idx = text.search(exportRe);
    if (idx < 0) {
      continue;
    }
    const lineStart = text.lastIndexOf("\n", idx) + 1;
    const lineEnd = text.indexOf("\n", idx);
    const snippet = text
      .slice(lineStart, lineEnd < 0 ? undefined : lineEnd)
      .trim();
    return {
      name,
      file: relative(UNIVERSE_DRIZZLE, file),
      snippet,
    };
  }
  return null;
}

function renderSurface() {
  const lines = [
    "/** AUTO-GENERATED by framework/runtime/scripts/gen-drizzle-surface.mjs — do not edit */",
    "",
    "// Cheap sqlite/D1 surface. Real signatures cannot be copied — see",
    "// framework/runtime/scripts/drizzle-seams.mjs and",
    "// docs/notes/2026-08-14-generator-spike.md.",
    `// Support: ${Object.entries(SUPPORT_WHY)
      .map(([k, v]) => `${k}: ${v}`)
      .join(" ")}`,
    `// ${QUERY_ANY_WHY}`,
    "",
    SUPPORT,
    "",
  ];
  for (const seam of NAME_SEAMS) {
    lines.push(`// ${seam.name}: ${seam.why}`);
    lines.push(seam.decl);
    lines.push("");
  }
  return `${lines.join("\n").trim()}\n`;
}

export function emitDrizzleSurface() {
  const missing = [];
  const hits = [];
  for (const seam of NAME_SEAMS) {
    const hit = findExport(seam.name);
    if (hit) {
      hits.push(hit);
    } else {
      missing.push(seam.name);
    }
  }
  if (missing.length > 0) {
    throw new Error(
      `drizzle types pack: seam name(s) missing from universe drizzle-orm: ${missing.join(", ")}`
    );
  }
  mkdirSync(generatedDir, { recursive: true });
  const text = renderSurface();
  writeFileSync(GENERATED_SURFACE_ABS, text);
  return { text, hits, path: GENERATED_SURFACE_ABS };
}

const isMain =
  Boolean(process.argv[1]) &&
  fileURLToPath(import.meta.url) === resolve(process.argv[1]);

if (isMain) {
  const result = emitDrizzleSurface();
  console.log(
    JSON.stringify({
      wrote: result.path,
      bytes: Buffer.byteLength(result.text),
      seams: NAME_SEAMS.length,
      universeHits: result.hits.map((h) => ({
        name: h.name,
        file: h.file,
        snippet: h.snippet.slice(0, 160),
      })),
    })
  );
}
